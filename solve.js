// solve.js — a faster drop-in for makefun-site 1.0.0 (site-generator-speed-01).
// Written from scratch from the reference's README and code; every output must be
// byte-identical to makefun-site 1.0.0's build. Single file, no dependencies, Node 22.
// Optimisations over the reference: bulk HTML escaping (no per-character regex),
// char-code line classification (no per-line regexes), range-based inline rendering
// (no substring copies for nested markup), a memoised slugify, and no re-split of
// a body the front-matter parser already split.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** Append `s[start..end)` HTML-escaped to `out`, using native replaces (the run holds a character to escape). */
function escapeReplaced(out, s, start, end) {
  out.push(s.slice(start, end).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;'));
}

/** Append `s[start..end)` HTML-escaped to `out` (an array of string pieces). */
function escapeInto(out, s, start, end) {
  if (start >= end) return;
  const chunk = s.slice(start, end);
  if (chunk.indexOf('&') === -1 && chunk.indexOf('<') === -1 && chunk.indexOf('>') === -1 && chunk.indexOf('"') === -1 && chunk.indexOf("'") === -1) {
    out.push(chunk);
    return;
  }
  out.push(chunk.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;'));
}

const SLUG_MAX = 64;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** The slug of `text`, exactly as the reference's slugify. `cache` memoises it per case. */
function slugify(text, cache) {
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  let out;
  // Fast path: pure ASCII has an identity NFKD and no combining marks.
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) { ascii = false; break; }
  }
  if (ascii) {
    let s = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = s.length > 0;
        continue;
      }
      if (gap) s += '-';
      gap = false;
      s += keep;
    }
    out = s.slice(0, SLUG_MAX).replace(/-+$/, '');
  } else {
    const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
    let s = '';
    let gap = false;
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = s.length > 0;
        continue;
      }
      if (gap) s += '-';
      gap = false;
      s += keep;
    }
    out = s.slice(0, SLUG_MAX).replace(/-+$/, '');
  }
  if (out === '') out = 'untitled';
  cache.set(text, out);
  return out;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  const y = date.slice(0, 4);
  const m = Number(date.slice(5, 7));
  const d = Number(date.slice(8, 10));
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

/** The words of a body: its runs of characters other than whitespace. */
function wordsOf(text) {
  const m = text.match(/\S+/g);
  return m === null ? 0 : m.length;
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

/** A string value: "..." with \" and \\ its only escapes, or bare. */
function stringOf(raw) {
  if (raw.charCodeAt(0) === 34) {
    if (raw.length < 2 || raw.charCodeAt(raw.length - 1) !== 34) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function isDigit(c) {
  return c >= '0' && c <= '9';
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      // YYYY-MM-DD, a real day from 1970-01-01 to 2099-12-31.
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      if (ok) {
        for (let i = 0; i < 10; i++) {
          if (i === 4 || i === 7) continue;
          if (!isDigit(raw[i])) { ok = false; break; }
        }
      }
      const y = ok ? Number(raw.slice(0, 4)) : 0;
      const mo = ok ? Number(raw.slice(5, 7)) : 0;
      const d = ok ? Number(raw.slice(8, 10)) : 0;
      if (!ok || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) {
        return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      return { value: raw };
    }
    case 'tags': {
      if (raw.charCodeAt(0) !== 91 || raw.charCodeAt(raw.length - 1) !== 93) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      // a-z and 0-9, single "-" between, at most 64 characters.
      if (raw.length === 0 || raw.length > 64) return { error: 'key "slug": not a slug' };
      let prevDash = true; // a slug may not open on "-"
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if (c === '-') {
          if (prevDash) return { error: 'key "slug": not a slug' };
          prevDash = true;
        } else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) {
          prevDash = false;
        } else return { error: 'key "slug": not a slug' };
      }
      if (prevDash) return { error: 'key "slug": not a slug' };
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter: { data, lines, bodyStart } — `lines` is the source split on
 * "\n" and the body starts at `bodyStart` — or { error } with the first reason refused.
 */
function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') { close = i; break; }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (isBlankLine(line) || line.charCodeAt(0) === 35) continue; // blank or "#..." comment
    const colon = line.indexOf(':');
    if (colon === -1) return { error: `line ${i + 1} is not "key: value"` };
    const key = line.slice(0, colon);
    let keyOk = key.length > 0;
    if (keyOk) {
      for (let k = 0; k < key.length; k++) {
        const c = key[k];
        if (!((c >= 'a' && c <= 'z') || c === '_')) { keyOk = false; break; }
      }
    }
    if (!keyOk) return { error: `line ${i + 1} is not "key: value"` };
    let raw;
    if (colon === line.length - 1) raw = '';
    else if (line.charCodeAt(colon + 1) === 32) raw = line.slice(colon + 2);
    else return { error: `line ${i + 1} is not "key: value"` };
    raw = raw.replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, lines, bodyStart: close + 1 };
}

// ---------------------------------------------------------------- markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

function isLangChar(c) {
  return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-';
}

/** Fence open: the language after ```, or "" with no language, or null when not a fence. */
function fenceOpen(line) {
  if (!line.startsWith('```')) return null;
  let i = 3;
  const langStart = i;
  while (i < line.length && isLangChar(line[i])) i++;
  const lang = line.slice(langStart, i);
  while (i < line.length && (line[i] === ' ' || line[i] === '\t')) i++;
  return i === line.length ? lang : null;
}

function fenceClose(line) {
  if (!line.startsWith('```')) return false;
  let i = 3;
  while (i < line.length && (line[i] === ' ' || line[i] === '\t')) i++;
  return i === line.length;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length || (line[n] !== ' ' && line[n] !== '\t')) return null;
  const text = trimLine(line.slice(n));
  return text === '' ? null : { depth: n, text };
}

function isHr(line) {
  if (line !== '---' && line !== '***' && !line.startsWith('--- ') && !line.startsWith('---\t') && !line.startsWith('*** ') && !line.startsWith('***\t')) {
    // also "---" / "***" followed only by spaces/tabs
    return false;
  }
  if (line === '---' || line === '***') return true;
  const rest = line.slice(3);
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] !== ' ' && rest[i] !== '\t') return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

const CONTINUED = /^ {2,}\S/;

/** `lines[start..]` block tokens, in order. */
function lex(lines, start) {
  const tokens = [];
  let i = start;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) { i++; continue; }
    const fence = fenceOpen(line);
    if (fence !== null) {
      const body = [];
      i++;
      while (i < n && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      tokens.push({ type: 'code', lang: fence, lines: body });
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      tokens.push({ type: 'heading', depth: heading.depth, text: heading.text });
      i++;
      continue;
    }
    if (isHr(line)) { tokens.push({ type: 'hr' }); i++; continue; }
    if (line.charCodeAt(0) === 62) { // '>'
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.startsWith('> ') ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      tokens.push({ type: 'blockquote', lines: kept });
      continue;
    }
    const c0 = line.charCodeAt(0);
    let marker = null;
    let ordered = false;
    let startNum = 1;
    let itemText = null;
    if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) { // "- " or "* "
      marker = 'bullet';
      itemText = line.slice(2);
    } else if (c0 >= 48 && c0 <= 57) {
      let j = 1;
      while (j < line.length && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
      if (j >= 1 && j <= 9 && line.charCodeAt(j) === 46 && line.charCodeAt(j + 1) === 32) {
        marker = 'ordered';
        ordered = true;
        startNum = Number(line.slice(0, j));
        itemText = line.slice(j + 2);
      }
    }
    if (marker !== null) {
      const items = [[trimLine(itemText)]];
      i++;
      while (i < n) {
        const l = lines[i];
        let m = null;
        if (marker === 'bullet') {
          const d0 = l.charCodeAt(0);
          if ((d0 === 45 || d0 === 42) && l.charCodeAt(1) === 32) m = l.slice(2);
        } else {
          let j = 0;
          while (j < l.length && l.charCodeAt(j) >= 48 && l.charCodeAt(j) <= 57) j++;
          if (j >= 1 && j <= 9 && l.charCodeAt(j) === 46 && l.charCodeAt(j + 1) === 32) m = l.slice(j + 2);
        }
        if (m !== null) {
          items.push([trimLine(m)]);
          i++;
        } else if (CONTINUED.test(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
        } else break;
      }
      tokens.push({ type: 'list', ordered, start: startNum, items: items.map((parts) => parts.join('\n')) });
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    tokens.push({ type: 'paragraph', text: body.join('\n') });
  }
  return tokens;
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  for (let j = from; j <= end - wlen; j++) {
    if (s[j] === '\\' && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** `s[start..end)` rendered inline into `out`; `env.link(target)` is a link's href. */
function inlineRange(s, start, end, env, out) {
  let i = start;
  while (i < end) {
    let j = i;
    let hasEsc = false;
    while (j < end) {
      const c = s[j];
      if (c === '\\' || c === '`' || c === '*' || c === '[') break;
      if (c === '&' || c === '<' || c === '>' || c === '"' || c === "'") hasEsc = true;
      j++;
    }
    if (j > i) {
      if (hasEsc) escapeReplaced(out, s, i, j);
      else out.push(s.slice(i, j));
    }
    if (j >= end) break;
    i = j;
    const c = s[i];
    if (c === '\\' && i + 1 < end && ESCAPABLE.has(s[i + 1])) {
      const e = ESCAPES[s[i + 1]];
      out.push(e === undefined ? s[i + 1] : e);
      i += 2;
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', i + 1);
      if (k !== -1 && k < end && k > i + 1) {
        out.push('<code>');
        escapeInto(out, s, i + 1, k);
        out.push('</code>');
        i = k + 1;
      } else {
        out.push('`');
        i++;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const k = findUnescaped(s, '**', i + 2, end);
        if (k > i + 2) {
          out.push('<strong>');
          inlineRange(s, i + 2, k, env, out);
          out.push('</strong>');
          i = k + 2;
        } else {
          out.push('**');
          i += 2;
        }
        continue;
      }
      const k = findSingleStar(s, i + 1, end);
      if (k > i + 1) {
        out.push('<em>');
        inlineRange(s, i + 1, k, env, out);
        out.push('</em>');
        i = k + 1;
      } else {
        out.push('*');
        i++;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1, end);
      let m = -1;
      if (k !== -1 && k + 1 < end && s[k + 1] === '(') {
        const r = s.indexOf(')', k + 2);
        if (r !== -1 && r < end) m = r;
      }
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        const href = env.link(target);
        out.push('<a href="');
        escapeInto(out, href, 0, href.length);
        out.push('">');
        inlineRange(s, i + 1, k, env, out);
        out.push('</a>');
        i = m + 1;
        continue;
      }
      out.push('[');
      i++;
      continue;
    }
    // A lone backslash (next char not escapable, or at the end) is itself.
    out.push('\\');
    i++;
  }
}

/**
 * `lines[start..]` rendered: its HTML (each block on its own lines, a "\n" after the
 * last), its table of contents and its excerpt (the first paragraph's inline HTML, or "").
 */
function renderMarkdown(lines, start, env, slugCache) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  for (const t of lex(lines, start)) {
    switch (t.type) {
      case 'heading': {
        const id = uniqueSlug(slugify(t.text, slugCache), ids);
        const parts = [];
        inlineRange(t.text, 0, t.text.length, env, parts);
        const html = parts.join('');
        blocks.push(`<h${t.depth} id="${id}">${html}</h${t.depth}>`);
        if (t.depth === 2 || t.depth === 3) toc.push({ level: t.depth, id, html });
        break;
      }
      case 'code': {
        const parts = ['<pre><code'];
        if (t.lang !== '') {
          parts.push(' class="language-');
          escapeInto(parts, t.lang, 0, t.lang.length);
          parts.push('"');
        }
        parts.push('>');
        for (const l of t.lines) {
          escapeInto(parts, l, 0, l.length);
          parts.push('\n');
        }
        parts.push('</code></pre>');
        blocks.push(parts.join(''));
        break;
      }
      case 'hr':
        blocks.push('<hr>');
        break;
      case 'blockquote': {
        if (t.lines.length === 0) {
          blocks.push('<blockquote>\n</blockquote>');
        } else {
          const joined = t.lines.join('\n');
          const parts = [];
          inlineRange(joined, 0, joined.length, env, parts);
          blocks.push(`<blockquote>\n<p>${parts.join('')}</p>\n</blockquote>`);
        }
        break;
      }
      case 'list': {
        const tag = t.ordered ? 'ol' : 'ul';
        const open = t.ordered && t.start !== 1 ? `<ol start="${t.start}">` : `<${tag}>`;
        const parts = [`${open}\n`];
        for (const item of t.items) {
          const ip = [];
          inlineRange(item, 0, item.length, env, ip);
          parts.push(`<li>${ip.join('')}</li>\n`);
        }
        parts.push(`</${tag}>`);
        blocks.push(parts.join(''));
        break;
      }
      case 'paragraph': {
        const parts = [];
        inlineRange(t.text, 0, t.text.length, env, parts);
        const html = parts.join('');
        if (excerpt === null) excerpt = html;
        blocks.push(`<p>${html}</p>`);
        break;
      }
    }
  }
  const htmlParts = [];
  for (let bi = 0; bi < blocks.length; bi++) {
    htmlParts.push(blocks[bi]);
    htmlParts.push('\n');
  }
  return { html: htmlParts.join(''), toc, excerpt: excerpt ?? '' };
}

